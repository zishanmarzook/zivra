#!/usr/bin/env python3
"""Generate a reproducible, offline Studio Command Bar installer from src/. No downloads at install time."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def quote(text):
    eq='='
    while ']'+eq+']' in text: eq+='='
    return '['+eq+'[\n'+text+']'+eq+']'
groups={'shared':('ReplicatedStorage','ZIVRA','Folder'),
        'server':('ServerScriptService','ZIVRA_Server','Script'),
        'client':('StarterPlayerScripts','ZIVRA_Client','LocalScript')}
entries=[]
for group,(service,name,kind) in groups.items():
    files=[]
    for path in sorted((root/'src'/group).glob('*.luau'), key=lambda path: path.name):
        filename=path.name
        child='' if filename.startswith('init.') else path.stem
        files.append('{name='+quote(child)+',source='+quote(path.read_text(encoding="utf-8"))+'}')
    entries.append('{service='+quote(service)+',name='+quote(name)+',class='+quote(kind)+',files={'+',\n'.join(files)+'}}')
header='''-- GENERATED by scripts/build_installer.py. Edit src/, then regenerate.
-- Run in Studio Command Bar, EDIT mode, in your EXISTING ZIVRA place.
-- Refuses conflicting installations; never deletes existing maps or scripts.
assert(not game:GetService("RunService"):IsRunning(), "Stop Play before installing ZIVRA")
local groups={
'''
footer='''
}
local destinations={
 ReplicatedStorage=game:GetService("ReplicatedStorage"),
 ServerScriptService=game:GetService("ServerScriptService"),
 StarterPlayerScripts=game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts"),
}
for _,g in ipairs(groups) do
 assert(not destinations[g.service]:FindFirstChild(g.name),g.name.." already exists. Use Rojo for updates; do not install a second copy.")
end
local staged={}
local ok,err=pcall(function()
 for _,g in ipairs(groups) do
  local root=Instance.new(g.class); root.Name=g.name; root:SetAttribute("ZIVRA_InstallVersion",1)
  table.insert(staged,{root=root,parent=destinations[g.service]})
  for _,f in ipairs(g.files) do
   if f.name=="" then root.Source=f.source
   else local m=Instance.new("ModuleScript"); m.Name=f.name; m.Source=f.source; m.Parent=root end
  end
 end
end)
if not ok then for _,x in ipairs(staged) do x.root:Destroy() end; error(err) end
local history=game:GetService("ChangeHistoryService")
local recording=history:TryBeginRecording("InstallZIVRACombat")
for _,x in ipairs(staged) do x.root.Parent=x.parent end
-- Explicit test-only opt-in. Live servers NEVER use or save fallback profiles.
workspace:SetAttribute("ZIVRA_OfflineProfiles",true)
if recording then history:FinishRecording(recording,Enum.FinishRecordingOperation.Commit) end
print("ZIVRA installed. Existing lobby/maps preserved. Save, then Play; use the Range kiosk or RANGE button.")
print("Studio fallback profiles are UNSAVED when DataStore access is unavailable. See docs/SETUP.md.")
'''
(root/'studio/InstallZivra.lua').write_text(header+',\n'.join(entries)+footer,encoding='utf-8')
print('Generated studio/InstallZivra.lua')
